def build_k_grid(k_min=0.0, k_max=5.0, step_coarse=0.1, step_fine=0.02, critical_lo=0.8, critical_hi=1.2):
    ks = []
    k = k_min
    while k <= k_max + 1e-12:
        ks.append(round(k, 4))
        if critical_lo <= k <= critical_hi:
            k += step_fine
        else:
            k += step_coarse
    return np.unique(np.array(ks, dtype=float))

def er_graph(N, k_avg, seed=None):
    p = k_avg / (N - 1)
    return nx.erdos_renyi_graph(n=N, p=p, seed=seed, directed=False)

def compute_S_and_savg(G):

    comps = list(nx.connected_components(G))
    sizes = np.array([len(c) for c in comps], dtype=float)
    if sizes.size == 0:
        return 0.0, 0.0

    NG = float(sizes.max())
    S = NG / G.number_of_nodes()

    if sizes.size == 1:
        s_avg = 0.0
    else:
        idx = int(np.argmax(sizes))
        rest = np.delete(sizes, idx)
        s_avg = float(np.mean(rest)) if rest.size > 0 else 0.0

    return S, s_avg

def sweep_k(N=1000, realizations=50, desc_prefix="", **grid_kwargs):

    ks = build_k_grid(**grid_kwargs)
    S_mean = np.zeros_like(ks, dtype=float)
    s_mean = np.zeros_like(ks, dtype=float)

    outer = tqdm(range(len(ks)), desc=f"{desc_prefix} Sweep <k> (N={N})", leave=True)
    for i in outer:
        k_avg = float(ks[i])

        Ss = []
        ss = []

        inner = tqdm(range(realizations), desc=f"  realizations @ <k>={k_avg:.2f}", leave=False)
        for r in inner:
            seed = SEED + (i + 1) * 100000 + r
            G = er_graph(N, k_avg, seed=seed)
            S, s_avg = compute_S_and_savg(G)
            Ss.append(S)
            ss.append(s_avg)

        S_mean[i] = float(np.mean(Ss))
        s_mean[i] = float(np.mean(ss))

        outer.set_postfix({"<k>": f"{k_avg:.2f}", "S": f"{S_mean[i]:.3f}", "<s>": f"{s_mean[i]:.3f}"})

    return ks, S_mean, s_mean

