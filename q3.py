def fit_alpha(bin_centers, P, s_min_fit=10):
    """Fit log10(P) = a - alpha log10(s) for s >= s_min_fit."""
    s = np.asarray(bin_centers)
    p = np.asarray(P)
    mask = (s >= s_min_fit) & (p > 0)
    x = np.log10(s[mask])
    y = np.log10(p[mask])
    if x.size < 2:
        return None
    m, a = np.polyfit(x, y, 1)
    alpha = -m
    return float(alpha), float(m), float(a)

