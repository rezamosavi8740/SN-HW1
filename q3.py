def log_binned_distribution(sizes, num_bins=30):
    """Return (bin_centers, P(bin)) with log-spaced bins."""
    sizes = np.asarray(sizes, dtype=int)
    sizes = sizes[sizes > 0]
    s_min = sizes.min()
    s_max = sizes.max()

    edges = np.unique(np.logspace(np.log10(s_min), np.log10(s_max), num_bins).astype(int))
    edges = np.unique(np.concatenate([edges, [s_max + 1]]))
    edges = np.sort(edges)

    counts, bin_edges = np.histogram(sizes, bins=edges)
    left = bin_edges[:-1]
    right = bin_edges[1:]
    centers = np.sqrt(left * right)  # geometric mean
    P = counts / counts.sum() if counts.sum() > 0 else counts.astype(float)

    mask = counts > 0
    return centers[mask].astype(float), P[mask].astype(float)

